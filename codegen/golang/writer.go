package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// fileWriter accumulates the body of one generated Go file and the imports it
// needs. The final source is formatted with go/format by Render.
type fileWriter struct {
	pkg     string
	doc     string
	body    bytes.Buffer
	imports map[string]string
	indent  int
}

func newFileWriter(pkg, doc string) *fileWriter {
	return &fileWriter{
		pkg:     pkg,
		doc:     doc,
		imports: make(map[string]string),
	}
}

// AddImport records an import path and optional alias. An empty alias means the
// import is used under the package's declared name.
func (w *fileWriter) AddImport(path, alias string) {
	if path == "" {
		return
	}
	if _, exists := w.imports[path]; !exists {
		w.imports[path] = alias
	}
}

// Line writes one line at the current indentation.
func (w *fileWriter) Line(format string, args ...any) {
	if format != "" {
		text := fmt.Sprintf(format, args...)
		for i := 0; i < w.indent; i++ {
			w.body.WriteByte('\t')
		}
		w.body.WriteString(text)
	}
	w.body.WriteByte('\n')
}

// Comment writes a Go line comment for each line in text.
func (w *fileWriter) Comment(text string) {
	if text == "" {
		return
	}
	text = strings.ReplaceAll(text, "\r\n", "\n")
	text = strings.ReplaceAll(text, "\r", "\n")
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			w.Line("//")
			continue
		}
		w.Line("// %s", line)
	}
}

// In increases the indentation level.
func (w *fileWriter) In() { w.indent++ }

// Out decreases the indentation level.
func (w *fileWriter) Out() {
	if w.indent > 0 {
		w.indent--
	}
}

// Indent runs fn one indentation level deeper.
func (w *fileWriter) Indent(fn func()) {
	w.In()
	fn()
	w.Out()
}

// Render builds a complete, formatted Go source file.
func (w *fileWriter) Render() ([]byte, error) {
	var src bytes.Buffer
	src.WriteString("// Code generated by gosmithy. DO NOT EDIT.\n\n")
	if w.doc != "" {
		for _, line := range strings.Split(strings.ReplaceAll(w.doc, "\r\n", "\n"), "\n") {
			line = strings.TrimRight(line, " \t")
			if line == "" {
				src.WriteString("//\n")
			} else {
				src.WriteString("// " + line + "\n")
			}
		}
	}
	fmt.Fprintf(&src, "package %s\n\n", w.pkg)

	if len(w.imports) > 0 {
		paths := make([]string, 0, len(w.imports))
		for path := range w.imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		src.WriteString("import (\n")
		for _, path := range paths {
			alias := w.imports[path]
			if alias != "" {
				fmt.Fprintf(&src, "\t%s %s\n", alias, strconv.Quote(path))
			} else {
				fmt.Fprintf(&src, "\t%s\n", strconv.Quote(path))
			}
		}
		src.WriteString(")\n\n")
	}

	src.Write(w.body.Bytes())
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated %s file: %w", w.pkg, err)
	}
	return formatted, nil
}

// mergeImports copies imports from other into w.
func (w *fileWriter) mergeImports(other *fileWriter) {
	for path, alias := range other.imports {
		w.AddImport(path, alias)
	}
}

func quoted(s string) string { return strconv.Quote(s) }
