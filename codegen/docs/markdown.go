package docs

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/tespeleta/gosmithy/codegen/openapi"
)

type operationView struct {
	Method string
	Path   string
	Op     *openapi.Operation
}

func renderMarkdown(doc *openapi.Document, links docLinks) []byte {
	var b strings.Builder
	b.WriteString("<!-- Code generated by gosmithy. DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&b, "# %s\n\n", doc.Info.Title)
	if doc.Info.Description != "" {
		b.WriteString(doc.Info.Description)
		b.WriteString("\n\n")
	}
	fmt.Fprintf(&b, "**API version:** `%s`\n\n", doc.Info.Version)
	if links.DescriptorHref != "" || links.IndexHref != "" {
		parts := make([]string, 0, 2)
		if links.DescriptorHref != "" {
			parts = append(parts, "[`openapi.json`]("+links.DescriptorHref+")")
		}
		if links.IndexHref != "" {
			parts = append(parts, "[Interactive API reference]("+links.IndexHref+")")
		}
		fmt.Fprintf(&b, "**OpenAPI:** %s\n\n", strings.Join(parts, " | "))
	}
	if doc.Internal {
		b.WriteString("> **Internal API.** This service is marked `@internal`.\n\n")
	}
	if doc.Deprecated {
		b.WriteString("> **Deprecated API.** This service is marked `@deprecated`.\n\n")
	}
	if doc.Since != "" {
		fmt.Fprintf(&b, "**Since:** %s\n\n", doc.Since)
	}
	if doc.Unstable {
		if doc.UnstableFeature != "" {
			fmt.Fprintf(&b, "> **Unstable API.** This service belongs to unstable feature `%s`.\n\n", doc.UnstableFeature)
		} else {
			b.WriteString("> **Unstable API.** This service is marked `@unstable`.\n\n")
		}
	}
	if len(doc.UnstableFeatures) > 0 {
		fmt.Fprintf(&b, "> **Unstable features:** %s\n\n", strings.Join(codeList(doc.UnstableFeatures), ", "))
	}
	if doc.ExternalDocs != nil {
		fmt.Fprintf(&b, "**External documentation:** %s\n\n", externalDocsLink(doc.ExternalDocs))
	}
	b.WriteString("> The interactive reference is a static page that loads `openapi.json` in the browser. Serve this directory over HTTP (for example with `python3 -m http.server`) rather than opening `index.html` from the filesystem.\n\n")

	operations := operationViews(doc)
	if len(operations) > 0 {
		b.WriteString("## Operations\n\n")
		b.WriteString("| Method | Path | Operation | Description |\n")
		b.WriteString("|---|---|---|---|\n")
		for _, view := range operations {
			fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | %s |\n",
				view.Method, view.Path, view.Op.OperationID, mdCell(view.Op.Summary))
		}
		b.WriteString("\n## Operation details\n\n")
		for _, view := range operations {
			renderOperation(&b, view)
		}
	}

	if doc.Components != nil && len(doc.Components.Schemas) > 0 {
		b.WriteString("## Data types\n\n")
		names := sortedMapKeys(doc.Components.Schemas)
		for _, name := range names {
			renderSchema(&b, name, doc.Components.Schemas[name])
		}
	}
	return []byte(b.String())
}

func operationViews(doc *openapi.Document) []operationView {
	paths := sortedMapKeys(doc.Paths)
	var views []operationView
	for _, path := range paths {
		item := doc.Paths[path]
		for _, candidate := range []struct {
			method string
			op     *openapi.Operation
		}{
			{"GET", item.Get},
			{"PUT", item.Put},
			{"POST", item.Post},
			{"DELETE", item.Delete},
			{"OPTIONS", item.Options},
			{"HEAD", item.Head},
			{"PATCH", item.Patch},
			{"TRACE", item.Trace},
		} {
			if candidate.op != nil {
				views = append(views, operationView{Method: candidate.method, Path: path, Op: candidate.op})
			}
		}
	}
	return views
}

func renderOperation(b *strings.Builder, view operationView) {
	op := view.Op
	fmt.Fprintf(b, "### `%s %s`\n\n", view.Method, view.Path)
	fmt.Fprintf(b, "**Operation ID:** `%s`\n\n", op.OperationID)
	flags := operationFlags(op)
	if flags != "" {
		b.WriteString(flags)
		b.WriteString("\n\n")
	}
	if len(op.Tags) > 0 {
		fmt.Fprintf(b, "**Tags:** %s\n\n", strings.Join(codeList(op.Tags), ", "))
	}
	if op.Description != "" {
		b.WriteString(op.Description)
		b.WriteString("\n\n")
	}
	if op.ExternalDocs != nil {
		fmt.Fprintf(b, "**External documentation:** %s\n\n", externalDocsLink(op.ExternalDocs))
	}

	if len(op.Parameters) > 0 {
		b.WriteString("**Parameters**\n\n")
		b.WriteString("| Name | In | Required | Type | Description | Constraints |\n")
		b.WriteString("|---|---|---|---|---|---|\n")
		for _, param := range op.Parameters {
			required := "no"
			if param.Required {
				required = "yes"
			}
			description := param.Description
			if param.Deprecated {
				description = joinNotes(description, "Deprecated")
			}
			if param.Internal {
				description = joinNotes(description, "Internal")
			}
			if param.Recommended {
				description = joinNotes(description, "Recommended")
			}
			if param.Unstable {
				description = joinNotes(description, unstableNote(param.UnstableFeature))
			}
			if param.Since != "" {
				description = joinNotes(description, "Since "+param.Since)
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s |\n",
				param.Name, param.In, required, schemaType(param.Schema), mdCell(description), schemaConstraints(param.Schema))
		}
		b.WriteString("\n")
		for _, param := range op.Parameters {
			renderExamples(b, fmt.Sprintf("Examples for parameter `%s`", param.Name), param.Examples)
		}
	}

	if op.RequestBody != nil {
		b.WriteString("**Request body**")
		if op.RequestBody.Required {
			b.WriteString(" (required)")
		}
		b.WriteString("\n\n")
		if op.RequestBody.Description != "" {
			b.WriteString(op.RequestBody.Description)
			b.WriteString("\n\n")
		}
		for _, contentType := range sortedMapKeys(op.RequestBody.Content) {
			mediaType := op.RequestBody.Content[contentType]
			fmt.Fprintf(b, "- `%s`: %s\n", contentType, schemaType(mediaType.Schema))
		}
		b.WriteString("\n")
		for _, contentType := range sortedMapKeys(op.RequestBody.Content) {
			mediaType := op.RequestBody.Content[contentType]
			fmt.Fprintf(b, "**Request body (`%s`)**\n\n", contentType)
			renderSchemaObject(b, mediaType.Schema)
			renderExamples(b, "Request examples", mediaType.Examples)
		}
	}

	if len(op.Responses) > 0 {
		b.WriteString("**Responses**\n\n")
		b.WriteString("| Status | Description | Content |\n")
		b.WriteString("|---|---|---|\n")
		for _, status := range sortedMapKeys(op.Responses) {
			response := op.Responses[status]
			fmt.Fprintf(b, "| `%s` | %s | %s |\n", status, mdCell(response.Description), responseContent(response))
		}
		b.WriteString("\n")
		for _, status := range sortedMapKeys(op.Responses) {
			response := op.Responses[status]
			if len(response.Headers) > 0 {
				fmt.Fprintf(b, "**Response `%s` headers**\n\n", status)
				b.WriteString("| Header | Type | Description | Constraints |\n")
				b.WriteString("|---|---|---|---|\n")
				for _, name := range sortedMapKeys(response.Headers) {
					header := response.Headers[name]
					fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n",
						name, schemaType(header.Schema), mdCell(header.Description), schemaConstraints(header.Schema))
				}
				b.WriteString("\n")
			}
			for _, contentType := range sortedMapKeys(response.Content) {
				mediaType := response.Content[contentType]
				fmt.Fprintf(b, "**Response `%s` body (`%s`)**\n\n", status, contentType)
				renderSchemaObject(b, mediaType.Schema)
				renderExamples(b, fmt.Sprintf("Examples for response `%s`", status), mediaType.Examples)
			}
		}
	}
}

func renderSchema(b *strings.Builder, name string, schema *openapi.Schema) {
	if schema == nil {
		return
	}
	fmt.Fprintf(b, "### `%s`\n\n", name)
	flags := schemaFlags(schema)
	if flags != "" {
		b.WriteString(flags)
		b.WriteString("\n\n")
	}
	if schema.Description != "" {
		b.WriteString(schema.Description)
		b.WriteString("\n\n")
	}
	fmt.Fprintf(b, "**Type:** %s\n\n", schemaType(schema))
	if schema.ExternalDocs != nil {
		fmt.Fprintf(b, "**External documentation:** %s\n\n", externalDocsLink(schema.ExternalDocs))
	}
	if len(schema.Enum) > 0 {
		b.WriteString("**Values:**\n\n")
		for _, value := range schema.Enum {
			key := fmt.Sprintf("%v", value)
			fmt.Fprintf(b, "- `%s`", key)
			var notes []string
			if doc := schema.EnumDescriptions[key]; doc != "" {
				notes = append(notes, doc)
			}
			if containsString(schema.EnumDeprecated, key) {
				notes = append(notes, "Deprecated")
			}
			if since := schema.EnumSince[key]; since != "" {
				notes = append(notes, "Since "+since)
			}
			if len(notes) > 0 {
				fmt.Fprintf(b, " — %s", mdText(strings.Join(notes, "; ")))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	if len(schema.OneOf) > 0 {
		b.WriteString("**Variants:**\n\n")
		for _, variant := range schema.OneOf {
			title := variant.Title
			if title == "" {
				title = schemaType(variant)
			}
			description := variant.Description
			if description == "" && len(variant.Properties) == 1 {
				for _, property := range variant.Properties {
					description = property.Description
				}
			}
			fmt.Fprintf(b, "- **%s**: %s", mdText(title), schemaVariantType(variant))
			if description != "" {
				fmt.Fprintf(b, " — %s", mdText(description))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	if len(schema.Properties) > 0 {
		b.WriteString("| Property | Type | Required | Description | Constraints |\n")
		b.WriteString("|---|---|---|---|---|\n")
		required := requiredSet(schema.Required)
		for _, propertyName := range sortedMapKeys(schema.Properties) {
			property := schema.Properties[propertyName]
			description := property.Description
			if property.Deprecated {
				description = joinNotes(description, "Deprecated")
			}
			if property.Internal {
				description = joinNotes(description, "Internal")
			}
			if property.Recommended {
				description = joinNotes(description, "Recommended")
			}
			if property.Unstable {
				description = joinNotes(description, unstableNote(property.UnstableFeature))
			}
			if property.Since != "" {
				description = joinNotes(description, "Since "+property.Since)
			}
			isRequired := "no"
			if required[propertyName] {
				isRequired = "yes"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n",
				propertyName, schemaType(property), isRequired, mdCell(description), schemaConstraints(property))
		}
		b.WriteString("\n")
	}
}

func renderSchemaObject(b *strings.Builder, schema *openapi.Schema) {
	if schema == nil {
		return
	}
	fmt.Fprintf(b, "**Schema:** %s\n\n", schemaType(schema))
	if len(schema.Properties) == 0 || schema.Ref != "" {
		return
	}
	b.WriteString("| Property | Type | Required | Description | Constraints |\n")
	b.WriteString("|---|---|---|---|---|\n")
	required := requiredSet(schema.Required)
	for _, name := range sortedMapKeys(schema.Properties) {
		property := schema.Properties[name]
		isRequired := "no"
		if required[name] {
			isRequired = "yes"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n",
			name, schemaType(property), isRequired, mdCell(property.Description), schemaConstraints(property))
	}
	b.WriteString("\n")
}

func renderExamples(b *strings.Builder, title string, examples map[string]*openapi.Example) {
	if len(examples) == 0 {
		return
	}
	fmt.Fprintf(b, "**%s**\n\n", mdText(title))
	for _, name := range sortedMapKeys(examples) {
		example := examples[name]
		fmt.Fprintf(b, "**%s**\n\n", mdText(name))
		if example.Description != "" {
			b.WriteString(example.Description)
			b.WriteString("\n\n")
		}
		data, err := json.MarshalIndent(example.Value, "", "  ")
		if err != nil {
			data = []byte(fmt.Sprintf("%v", example.Value))
		}
		b.WriteString("```json\n")
		b.Write(data)
		b.WriteString("\n```\n\n")
	}
}

func operationFlags(op *openapi.Operation) string {
	var flags []string
	if op.Deprecated {
		flags = append(flags, "Deprecated")
	}
	if op.Internal {
		flags = append(flags, "Internal")
	}
	if op.Unstable {
		flags = append(flags, unstableNote(op.UnstableFeature))
	}
	if op.Since != "" {
		flags = append(flags, "Since "+op.Since)
	}
	if len(flags) == 0 {
		return ""
	}
	return "**" + strings.Join(flags, " · ") + "**"
}

func schemaFlags(schema *openapi.Schema) string {
	var flags []string
	if schema.Deprecated {
		flags = append(flags, "Deprecated")
	}
	if schema.Internal {
		flags = append(flags, "Internal")
	}
	if schema.Recommended {
		flags = append(flags, "Recommended")
	}
	if schema.Unstable {
		flags = append(flags, unstableNote(schema.UnstableFeature))
	}
	if schema.Synthetic {
		flags = append(flags, "Generated by the assembler")
	}
	if schema.Since != "" {
		flags = append(flags, "Since "+schema.Since)
	}
	if len(flags) == 0 {
		return ""
	}
	return "**" + strings.Join(flags, " · ") + "**"
}

func schemaType(schema *openapi.Schema) string {
	if schema == nil {
		return "`any`"
	}
	base := ""
	switch {
	case schema.Ref != "":
		base = "`" + shortRef(schema.Ref) + "`"
	case len(schema.OneOf) > 0:
		parts := make([]string, 0, len(schema.OneOf))
		for _, variant := range schema.OneOf {
			parts = append(parts, schemaVariantType(variant))
		}
		base = strings.Join(parts, " | ")
	case len(schema.AllOf) > 0:
		base = schemaType(schema.AllOf[0])
	case schema.Type == "array":
		base = "[]" + trimTypeTicks(schemaType(schema.Items))
	case schema.Type == "object" && schema.AdditionalProperties != nil:
		base = "map[string]" + trimTypeTicks(schemaType(schema.AdditionalProperties))
	case schema.Type == "object":
		base = "`object`"
	case schema.Type == "":
		base = "`any`"
	case schema.Format != "":
		base = "`" + schema.Type + "` (" + schema.Format + ")"
	default:
		base = "`" + schema.Type + "`"
	}
	if schema.Nullable {
		base += " or `null`"
	}
	return base
}

func schemaVariantType(schema *openapi.Schema) string {
	if schema == nil {
		return "`any`"
	}
	if len(schema.Properties) == 1 {
		for _, property := range schema.Properties {
			return schemaType(property)
		}
	}
	return schemaType(schema)
}

func trimTypeTicks(value string) string {
	return strings.Trim(value, "`")
}

func shortRef(ref string) string {
	const prefix = "#/components/schemas/"
	if strings.HasPrefix(ref, prefix) {
		ref = strings.TrimPrefix(ref, prefix)
	}
	ref = strings.ReplaceAll(ref, "~1", "/")
	ref = strings.ReplaceAll(ref, "~0", "~")
	return ref
}

func schemaConstraints(schema *openapi.Schema) string {
	if schema == nil {
		return "—"
	}
	var values []string
	if schema.Min != nil {
		values = append(values, fmt.Sprintf("min %v", *schema.Min))
	}
	if schema.Max != nil {
		values = append(values, fmt.Sprintf("max %v", *schema.Max))
	}
	if schema.MinLength != nil {
		values = append(values, fmt.Sprintf("min length %d", *schema.MinLength))
	}
	if schema.MaxLength != nil {
		values = append(values, fmt.Sprintf("max length %d", *schema.MaxLength))
	}
	if schema.MinItems != nil {
		values = append(values, fmt.Sprintf("min items %d", *schema.MinItems))
	}
	if schema.MaxItems != nil {
		values = append(values, fmt.Sprintf("max items %d", *schema.MaxItems))
	}
	if schema.MinProperties != nil {
		values = append(values, fmt.Sprintf("min properties %d", *schema.MinProperties))
	}
	if schema.MaxProperties != nil {
		values = append(values, fmt.Sprintf("max properties %d", *schema.MaxProperties))
	}
	if schema.Pattern != "" {
		values = append(values, "pattern `"+schema.Pattern+"`")
	}
	if schema.UniqueItems {
		values = append(values, "unique items")
	}
	if schema.Nullable {
		values = append(values, "nullable")
	}
	if len(values) == 0 {
		return "—"
	}
	return mdCell(strings.Join(values, ", "))
}

func responseContent(response *openapi.Response) string {
	if response == nil || len(response.Content) == 0 {
		return "—"
	}
	var values []string
	for _, contentType := range sortedMapKeys(response.Content) {
		values = append(values, "`"+contentType+"`: "+schemaType(response.Content[contentType].Schema))
	}
	return strings.Join(values, "<br>")
}

func externalDocsLink(docs *openapi.ExternalDocs) string {
	if docs == nil {
		return ""
	}
	label := docs.Description
	if label == "" {
		label = "External documentation"
	}
	return fmt.Sprintf("[%s](%s)", mdText(label), docs.URL)
}

func containsString(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}

func requiredSet(required []string) map[string]bool {
	set := make(map[string]bool, len(required))
	for _, name := range required {
		set[name] = true
	}
	return set
}

func sortedMapKeys[T any](values map[string]T) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func codeList(values []string) []string {
	out := make([]string, 0, len(values))
	for _, value := range values {
		out = append(out, "`"+value+"`")
	}
	return out
}

func unstableNote(feature string) string {
	if feature == "" {
		return "Unstable"
	}
	return "Unstable (feature `" + feature + "`)"
}

func joinNotes(description, note string) string {
	if description == "" {
		return note
	}
	return description + " " + note
}

func mdText(value string) string {
	return strings.Join(strings.Fields(value), " ")
}

func mdCell(value string) string {
	value = mdText(value)
	value = strings.ReplaceAll(value, "|", "\\|")
	if value == "" {
		return "—"
	}
	return value
}
