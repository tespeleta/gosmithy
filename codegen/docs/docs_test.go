var updateGolden = flag.Bool("update-docs", false, "update docs golden files")

func assembleFixture(t *testing.T, path string) *model.Model {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	file, err := idl.ParseWithOptions(path, string(data), idl.Options{Version: idl.V2_1, DefaultVersion: idl.V2_0})
	if err != nil {
		t.Fatal(err)
	}
	m, err := model.Assemble([]*idl.File{file}, model.Options{})
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func docsRequest(t *testing.T) *codegen.Request {
	t.Helper()
	m := assembleFixture(t, filepath.Join("..", "..", "testdata", "docs.smithy"))
	return &codegen.Request{
		Model:    m,
		Service:  model.MustShapeID("example.docs#Docs"),
		Protocol: &codegen.Protocol{ID: httpjson.ID},
		Target: codegen.Target{
			Name:       "openapi:descriptor+openapi:index+docs:markdown",
			Generators: []string{"openapi:descriptor", "openapi:index", "docs:markdown"},
		},
	}
}

func TestGenerateDocs(t *testing.T) {
	response, err := New().Generate(context.Background(), docsRequest(t))
	if err != nil {
		t.Fatal(err)
	}
	for _, diagnostic := range response.Diagnostics {
		if diagnostic.Severity == model.SeverityDanger {
			t.Fatalf("unexpected danger: %s", diagnostic.String())
		}
	}
	files := make(map[string][]byte)
	for _, file := range response.Files {
		files[file.Path] = file.Content
	}
	if len(files) != 1 || len(files["docs/README.md"]) == 0 {
		t.Fatalf("files = %+v, want only docs/README.md", files)
	}
	md := string(files["docs/README.md"])
	for _, want := range []string{
		"# Docs Showcase",
		"Gets a book by id.",
		"Homepage",
		"Preview a book",
		"## Operations",
		"### `GET /books/{id}`",
		"### `Book`",
		"**Deprecated · Unstable (feature `preview`)**",
		"Examples for parameter `id`",
		"Request examples",
		"Create a book",
		"Examples for response `200`",
		"Examples for response `404`",
		"Internal",
		"Recommended",
		"Since 2.1.0",
		"`token` | `string` (password)",
		"Generated by the assembler",
		"Fiction and literature.",
		"Since 2.0.0",
		"Deprecated",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("README.md missing %q", want)
		}
	}
}

func TestGoldenMarkdown(t *testing.T) {
	response, err := New().Generate(context.Background(), docsRequest(t))
	if err != nil {
		t.Fatal(err)
	}
	var markdown []byte
	for _, file := range response.Files {
		if file.Path == "docs/README.md" {
			markdown = file.Content
		}
	}
	if len(markdown) == 0 {
		t.Fatal("missing docs/README.md")
	}
	golden := filepath.Join("testdata", "golden", "docs.readme.md")
	if *updateGolden {
		if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(golden, markdown, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(markdown, want) {
		t.Errorf("Markdown differs from %s; run go test ./codegen/docs -update-docs", golden)
	}
}

func TestNoProtocol(t *testing.T) {
	m := assembleFixture(t, filepath.Join("..", "..", "testdata", "docs.smithy"))
	req := &codegen.Request{Model: m, Service: model.MustShapeID("example.docs#Docs")}
	response, err := New().Generate(context.Background(), req)
	if err != nil {
		t.Fatal(err)
	}
	if len(response.Files) != 0 {
		t.Errorf("files = %+v", response.Files)
	}
	if len(response.Diagnostics) == 0 || response.Diagnostics[0].Severity != model.SeverityDanger {
		t.Fatalf("diagnostics = %+v", response.Diagnostics)
	}
}

func TestDeterministic(t *testing.T) {
	first, err := New().Generate(context.Background(), docsRequest(t))
	if err != nil {
		t.Fatal(err)
	}
	second, err := New().Generate(context.Background(), docsRequest(t))
	if err != nil {
		t.Fatal(err)
	}
	if len(first.Files) != len(second.Files) {
		t.Fatal("different file counts")
	}
	for i := range first.Files {
		if first.Files[i].Path != second.Files[i].Path || !bytes.Equal(first.Files[i].Content, second.Files[i].Content) {
			t.Errorf("file %d differs", i)
		}
	}
}

func TestMarkdownLinksDependOnSelectedOutputs(t *testing.T) {
	req := docsRequest(t)
	req.Target.Generators = []string{"openapi:descriptor", "docs:markdown"}
	response, err := New().Generate(context.Background(), req)
	if err != nil {
		t.Fatal(err)
	}
	var markdown string
	for _, file := range response.Files {
		if file.Path == "docs/README.md" {
			markdown = string(file.Content)
		}
	}
	if !strings.Contains(markdown, "(../openapi.json)") {
		t.Errorf("Markdown does not link the root descriptor:\n%s", markdown)
	}
	if strings.Contains(markdown, "(index.html)") {
		t.Errorf("Markdown links an index that was not selected:\n%s", markdown)
	}
}
